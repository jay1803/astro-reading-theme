/** Full date, UTC so builds are deterministic: "2026 年 11 月 24 日" / "Nov 24, 2026". */
export function formatDate(d: Date): string {
  if (isZh) return `${d.getUTCFullYear()} 年 ${d.getUTCMonth() + 1} 月 ${d.getUTCDate()} 日`;
  return d.toLocaleDateString('en-US', { month: 'short', day: 'numeric', year: 'numeric', timeZone: 'UTC' });
}

/** Zero-padded entry number: 7 -> "007". */
export function entryNumber(n: number): string {
  return String(n).padStart(3, '0');
}
